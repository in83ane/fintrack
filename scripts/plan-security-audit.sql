-- Read-only. Run AFTER the intended phase's migrations on the Supabase copy/project.
-- Missing rows are NOT proof of security: confirm the expected schema/functions exist.
select n.nspname,
 has_schema_privilege('anon',n.oid,'USAGE') as anon_usage,
 has_schema_privilege('authenticated',n.oid,'USAGE') as authenticated_usage
from pg_namespace n where n.nspname='plan_private';

select n.nspname,p.proname,p.prosecdef as security_definer,p.proconfig,
 has_function_privilege('anon',p.oid,'EXECUTE') as anon_execute,
 has_function_privilege('authenticated',p.oid,'EXECUTE') as authenticated_execute
from pg_proc p join pg_namespace n on n.oid=p.pronamespace
where n.nspname='plan_private' or (n.nspname='public' and p.proname in
 ('validate_daily_plan_rule','guard_plan_schedule','check_daily_plan','uncheck_daily_plan','protect_plan_expense','protect_plan_bucket_activity','protect_plan_bucket_identity'))
order by n.nspname,p.proname;

-- Effective dates are generated by the database trigger, not a client field.
select pg_get_functiondef(p.oid) as trigger_definition
from pg_proc p join pg_namespace n on n.oid=p.pronamespace
where n.nspname='plan_private' and p.proname='capture_rule_version';

-- Phase 2: all three rows must exist, RLS=true, SELECT=true and writes=false.
select c.relname,c.relrowsecurity,
 has_table_privilege('authenticated',c.oid,'SELECT') as client_read,
 has_table_privilege('authenticated',c.oid,'INSERT') as client_insert,
 has_table_privilege('authenticated',c.oid,'UPDATE') as client_update,
 has_table_privilege('authenticated',c.oid,'DELETE') as client_delete
from pg_class c join pg_namespace n on n.oid=c.relnamespace
where n.nspname='public' and c.relname in ('plan_month_locks','plan_status_events','plan_system_buckets');
