import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import ts from 'typescript';
const source=readFileSync(new URL('../src/components/CostBasisPanel.tsx',import.meta.url),'utf8');
const start=source.indexOf('{!snapshot?<div role="status"');
const end=source.indexOf(':<motion.div',start);
assert.ok(start>0&&end>start);
const jsx=source.slice(start+'{!snapshot?'.length,end);
const compiled=ts.transpileModule(`function Loading({error}){return ${jsx};}`,{compilerOptions:{jsx:ts.JsxEmit.React,target:ts.ScriptTarget.ES2022}}).outputText;
const Loading=new Function('React',`${compiled};return Loading;`)(React);
const html=renderToStaticMarkup(React.createElement(Loading,{error:''}));
assert.match(html,/role="status"/);
assert.match(html,/min-h-\[300px\]/);
assert.match(html,/กำลังตรวจสอบ ledger/);
assert.ok(!html.includes('<button')&&!html.includes('<input'),'no actionable stale holdings while loading');
assert.ok(!html.includes('animate-pulse'),'no loading pulse that resembles flicker');
assert.match(source,/min-h-\[380px\] sm:min-h-\[340px\]/);
assert.match(source,/duration:reduceMotion\?0:0.18/);
assert.match(renderToStaticMarkup(React.createElement(Loading,{error:'network'})),/ยังโหลดข้อมูลไม่สำเร็จ/);
console.log('PASS: reserved loading space, static skeleton, error state, no sale controls, reduced-motion transition.');
